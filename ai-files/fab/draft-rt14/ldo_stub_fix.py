#!/usr/bin/env python3
"""ldo_stub_fix.py BOARD.kicad_pcb [-o OUT.kicad_pcb] [--dry-run]
Release to-do step 1.2 (RT-15): remove the dead /USB_PD/LDO_3V3 stub north of J4-1. Plain python3, text level, idempotent.

  delete  via (133.85, 40.6), via (133.85, 38.35) and the F.Cu segment (133.85, 40.6)-(133.85, 38.35)  [net LDO_3V3]
  shorten the In2.Cu segment (133.85, 45.4)-(133.85, 40.6) so that it ends at (133.85, 42.5) (inside the J4-1 pad)
  remove teardrop zones of net LDO_3V3 with a vertex within 0.8 mm of a deleted via or the old In2 end (they are
  regenerated by `kicad-cli pcb drc --refill-zones --save-board`; see regen_final.sh --teardrops)

Items are found by net and coordinates (0.002 mm), not by uuid. A second run finds nothing to do and writes an identical file.
Exit 0 on success (also when already applied), 2 if the board matches neither the original nor the fixed state."""
import re, sys, math, argparse

NET = '/USB_PD/LDO_3V3'
X = 133.85
VIAS = [(X, 40.6), (X, 38.35)]
FSEG = ((X, 40.6), (X, 38.35))
IN2_OLD = ((X, 45.4), (X, 40.6))
IN2_NEW_END = (X, 42.5)
TOL = 0.002
NUM = r'(-?[\d.]+)'

ap = argparse.ArgumentParser()
ap.add_argument('board'); ap.add_argument('-o', '--out'); ap.add_argument('--dry-run', action='store_true')
a = ap.parse_args()
L = open(a.board, encoding='utf-8').read().split('\n')


def blocks():
    i = 0
    while i < len(L):
        m = re.match(r'^\t\((segment|via|zone)(?: |$)', L[i])
        if not m: i += 1; continue
        j = i
        while L[j] != '\t)': j += 1
        yield m.group(1), i, j
        i = j + 1


def top(i0, i1, key):
    for k in range(i0, i1 + 1):
        s = L[k]
        if s.startswith('\t\t(' + key + ' '): return k, s.strip()
    return None, None


def pt(s):
    m = re.match(r'^\((?:start|end|at) ' + NUM + ' ' + NUM, s); return (float(m.group(1)), float(m.group(2)))


def near(p, q, t=TOL): return abs(p[0] - q[0]) < t and abs(p[1] - q[1]) < t


def fmt(v):
    s = ('%.6f' % v).rstrip('0').rstrip('.'); return '0' if s in ('-0', '') else s


dele, setl, log, hot = set(), {}, [], list(VIAS) + [IN2_OLD[1]]
found = dict(via=0, fseg=0, in2_old=0, in2_new=0)
for kind, i0, i1 in blocks():
    txt = '\n'.join(L[i0:i1 + 1])
    if '(net "%s")' % NET not in txt: continue
    if kind == 'via':
        k, s = top(i0, i1, 'at'); p = pt(s)
        if any(near(p, v) for v in VIAS):
            dele.update(range(i0, i1 + 1)); found['via'] += 1; log.append('delete via %s' % (p,))
    elif kind == 'segment':
        ks, ss = top(i0, i1, 'start'); ke, se = top(i0, i1, 'end'); _, ly = top(i0, i1, 'layer')
        s, e = pt(ss), pt(se)
        pair = lambda A, B: (near(s, A) and near(e, B)) or (near(s, B) and near(e, A))
        if ly == '(layer "F.Cu")' and pair(*FSEG):
            dele.update(range(i0, i1 + 1)); found['fseg'] += 1; log.append('delete F.Cu segment %s-%s' % (s, e))
        elif ly == '(layer "In2.Cu")' and pair(*IN2_OLD):
            k = ke if near(e, IN2_OLD[1]) else ks
            tag = 'end' if k == ke else 'start'
            setl[k] = '\t\t(%s %s %s)' % (tag, fmt(IN2_NEW_END[0]), fmt(IN2_NEW_END[1]))
            found['in2_old'] += 1; log.append('shorten In2.Cu segment %s-%s -> end %s' % (s, e, IN2_NEW_END))
        elif ly == '(layer "In2.Cu")' and pair(IN2_OLD[0], IN2_NEW_END):
            found['in2_new'] += 1
    elif kind == 'zone' and '(teardrop' in txt:
        pts = [(float(x), float(y)) for x, y in re.findall(r'\(xy ' + NUM + ' ' + NUM + r'\)', txt)]
        if any(math.hypot(p[0] - h[0], p[1] - h[1]) < 0.8 for p in pts for h in hot):
            dele.update(range(i0, i1 + 1)); log.append('delete teardrop zone near the stub (%d pts)' % len(pts))

orig = found['via'] == 2 and found['fseg'] == 1 and found['in2_old'] == 1
fixed = found['via'] == 0 and found['fseg'] == 0 and found['in2_old'] == 0 and found['in2_new'] == 1
print('found', found)
for x in log: print(' ', x)
if not (orig or fixed):
    print('ERROR: board matches neither the RT-14 stub state nor the fixed state; nothing written'); sys.exit(2)
if fixed and not log:
    print('already applied: nothing to do')
if a.dry_run:
    print('dry run: nothing written'); sys.exit(0)
out = a.out or a.board
res = [setl.get(k, s) for k, s in enumerate(L) if k not in dele or k in setl]
open(out, 'w', encoding='utf-8').write('\n'.join(res))
print('wrote', out)
