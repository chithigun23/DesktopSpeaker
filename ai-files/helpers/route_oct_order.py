#!/usr/bin/env python3
"""route_oct_order.py GEO.json NETLIST.txt OUT_NETFILE : stage assignment by rule OR1 and order inside a stage by OR2.
S1 USB pair + clocks + I2S (classes USB, I2S_CLK); S2 analog audio (AUDIO) + amplifier I2C (/AUD_SDA, /AUD_SCL); S3 the rest.
Inside a stage: nets with fine-pitch pads first (pads <= 0.35 mm wide on parts with >= 3 pads), then by octilinear MST length, longest first.
USB_DN gets pair=/USB_DP; USB nets get bcu=gnd (B.Cu only over In2 GND, needed for the USB-C A/B row interleave)."""
import sys, json, math, collections
geo, lst, out = sys.argv[1:4]
D = json.load(open(geo)); nets = [l.strip() for l in open(lst) if l.strip()]
pads = collections.defaultdict(list)
for p in D['pads']:
    if p['net']:
        pads[p['net']].append(p)
npads = {r: c['npads'] for r, c in D['courtyard'].items()}
def octi(a, b):
    dx = abs(a['x'] - b['x']); dy = abs(a['y'] - b['y']); return max(dx, dy) + (math.sqrt(2) - 1) * min(dx, dy)
def mst(P):
    if len(P) < 2: return 0.0
    inT = {0}; d = [octi(P[0], q) for q in P]; t = 0.0
    while len(inT) < len(P):
        j = min((i for i in range(len(P)) if i not in inT), key=lambda i: d[i]); t += d[j]; inT.add(j)
        for i in range(len(P)): d[i] = min(d[i], octi(P[i], P[j]))
    return t
rows = []
for n in nets:
    c = D['netclass'].get(n, 'Default')
    st = 'S1' if c in ('USB', 'I2S_CLK') else 'S2' if (c == 'AUDIO' or n in ('/AUD_SDA', '/AUD_SCL')) else 'S3'
    fine = sum(1 for p in pads[n] if npads.get(p['ref'], 0) >= 3 and min(p['sx'], p['sy']) <= 0.35)
    rows.append((st, -min(fine, 1), -mst(pads[n]), n, c))
rows.sort()
PAIR = {'/USB_DN': '/USB_DP', 'Net-(U2-D-)': 'Net-(U2-D+)'}
for n, q in PAIR.items():        # a pair follower is routed right after its partner
    a = next((r for r in rows if r[3] == n), None); b = next((r for r in rows if r[3] == q), None)
    if a and b:
        rows.remove(a); rows.insert(rows.index(b) + 1, a)
with open(out, 'w') as f:
    f.write('# generated by route_oct_order.py from %s (OR1 stages, OR2 order: fine-pitch first, then longest MST)\n' % lst)
    for st, fi, m, n, c in rows:
        opt = ''
        if c == 'USB': opt += ' bcu=gnd'
        if n == '/USB_DN': opt += ' pair=/USB_DP'
        if n == 'Net-(U2-D-)': opt += ' pair=Net-(U2-D+)'
        f.write('%s %s%s   # %s mst %.1f%s\n' % (st, n, opt, c, -m, ' fine-pitch' if fi else ''))
print(collections.Counter(r[0] for r in rows))
